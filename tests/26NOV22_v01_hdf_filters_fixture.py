"""生成独立Bitshuffle测试夹具头文件（可选维护步骤，不是产品运行依赖）。

输入：h5py+hdf5plugin，确定性shape(2,35,67)数值；无业务文件。
输出：tests/hdf_filters_fixture.hpp，包含HDF5文件/原始chunk的base64字节。
运行：python tests/26NOV22_v01_hdf_filters_fixture.py；常规C++测试直接用已生成头文件。
"""
from pathlib import Path
import base64
import json
import tempfile
import h5py
import hdf5plugin
import numpy as np


def main():
    p_tests = Path(__file__).resolve().parent
    l_lines = ['// Generated by 26NOV22_v01_hdf_filters_fixture.py with h5py/hdf5plugin.',
               '// Independent encoder fixtures, no business data. Shape (2,35,67).', '#pragma once',
               'namespace HdfFilterFixture {']
    a_indices = np.arange(2 * 35 * 67).reshape(2, 35, 67)
    def emit(s_name, b_data):
        s_base64 = base64.b64encode(b_data).decode('ascii')
        l_lines.append('inline constexpr const char ' + s_name + '[] =')
        for i_start in range(0, len(s_base64), 100):
            l_lines.append('    "' + s_base64[i_start:i_start + 100] + '"')
        l_lines.append('    ;')
    with tempfile.TemporaryDirectory(prefix='tmp-hdf-filter-fixture-') as s_temp:
        for s_mode in ['none', 'lz4', 'zstd']:
            p_file = Path(s_temp) / (s_mode + '.h5')
            with h5py.File(p_file, 'w', libver='earliest') as o_file:
                for s_type in ['i4', 'u4', 'f8', '>i2']:
                    s_name = {'i4': 'signed', 'u4': 'unsigned', 'f8': 'floating', '>i2': 'bigendian'}[s_type]
                    a_data = (a_indices % 200 - 100).astype(s_type)
                    if s_type == 'u4':
                        a_data = (a_indices + 4000000000).astype(s_type)
                    if s_type == 'f8':
                        a_data = a_data * .125
                    o_dataset = o_file.create_dataset(s_name, data=a_data, chunks=(1, 35, 67), **hdf5plugin.Bitshuffle(cname=s_mode))
                    o_dataset.attrs['scale_factor'] = .0001
                    o_dataset.attrs['add_offset'] = 2.0
                    if s_type == 'i4':
                        o_dataset.attrs['_FillValue'] = np.int32(-100)
                        o_dataset.attrs['missing_value'] = np.int32(-99)
                i_mask, b_chunk = o_file['signed'].id.read_direct_chunk((0, 0, 0))
                assert i_mask == 0
            emit('file_' + s_mode, p_file.read_bytes())
            emit('chunk_' + s_mode, b_chunk)
    l_lines.append('}')
    (p_tests / 'hdf_filters_fixture.hpp').write_text('\n'.join(l_lines) + '\n', encoding='utf-8')
    print(json.dumps({'status': 'PASS', 'h5py': h5py.__version__, 'shape': [2, 35, 67], 'modes': 3, 'types': 4}))


if __name__ == '__main__':
    main()
